package main

import (
	"encoding/json"
	"fmt"
	"path"
	"path/filepath"
)

// ImageRegistry is where releases publish the component images, as
// <ImageRegistry>/kb-<component>:<version>.
const ImageRegistry = "ghcr.io/christophbe"

// Image is one container image: a module component, or the web shell.
type Image struct {
	Component  string `json:"component"`
	Image      string `json:"image"`
	Dockerfile string `json:"dockerfile"`
	// BuildArgs are KEY=value lines for docker/build-push-action, without
	// KB_VERSION (the workflow adds it).
	BuildArgs string `json:"build_args"`
}

// resolveCmd finds the Go main package of a Go service in
// modules/<id>/<component dir>/cmd/<name>, relative to the repository root.
func (s *Service) resolveCmd(moduleDir, id string) error {
	if s.Language != "go" {
		return nil
	}
	matches, err := filepath.Glob(filepath.Join(moduleDir, "*", "cmd", s.Name))
	if err != nil {
		return err
	}
	if len(matches) != 1 {
		return fmt.Errorf("service %s: want exactly one main package */cmd/%s, found %d", s.Name, s.Name, len(matches))
	}
	rel, err := filepath.Rel(moduleDir, matches[0])
	if err != nil {
		return err
	}
	s.Cmd = "./" + path.Join("modules", id, filepath.ToSlash(rel))
	return nil
}

// images lists every image a release publishes, in build order: the module
// components sorted by module id, then the web shell.
func images(modules []Module) []Image {
	var out []Image
	for _, m := range modules {
		for _, s := range m.Services {
			img := Image{Component: s.Name, Image: ImageRegistry + "/kb-" + s.Name}
			switch s.Language {
			case "go":
				img.Dockerfile = "deploy/docker/go.Dockerfile"
				img.BuildArgs = "CMD=" + s.Cmd
			case "python":
				// The workspace package and its console script are named kb-<component>.
				img.Dockerfile = "deploy/docker/python.Dockerfile"
				img.BuildArgs = "PACKAGE=kb-" + s.Name
			}
			out = append(out, img)
		}
	}
	return append(out, Image{Component: "web", Image: ImageRegistry + "/kb-web", Dockerfile: "deploy/docker/web.Dockerfile"})
}

// imagesJSON renders the images as a GitHub Actions matrix: its "include"
// key is the matrix ("//" carries the generated-file note JSON has no
// comments for).
func imagesJSON(modules []Module) ([]byte, error) {
	raw, err := json.MarshalIndent(map[string]any{
		"//":      "Code generated by modgen from modules/*/module.yaml. DO NOT EDIT. Read by .github/workflows/images.yml.",
		"include": images(modules),
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(raw, '\n'), nil
}
